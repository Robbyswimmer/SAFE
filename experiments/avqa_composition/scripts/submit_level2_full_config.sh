#!/bin/bash
# Submit a full-data Level-2 composition run (derivation-only defaults).
#
# Usage:
#   bash experiments/avqa_composition/scripts/submit_level2_full_config.sh
#
# Override any setting inline, e.g.:
#   EPOCHS=5 SEED=7 OUTPUT_DIR=checkpoints/my_run \
#   WANDB_RUN_NAME=my_run bash experiments/avqa_composition/scripts/submit_level2_full_config.sh
#
# Optional:
#   SBATCH_RESOURCES="--gres=gpu:1 --exclude=gpu03"
#   DRY_RUN=1   # print sbatch command without submitting

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SAFE_ROOT="${SAFE_ROOT:-$(cd "$SCRIPT_DIR/../../.." && pwd)}"
TRAIN_SCRIPT="$SAFE_ROOT/experiments/avqa_composition/scripts/train_composition_interleaved.sh"

if [[ ! -f "$TRAIN_SCRIPT" ]]; then
  echo "[error] train script not found: $TRAIN_SCRIPT" >&2
  exit 1
fi

# -----------------------------
# Cluster / submit settings
# -----------------------------
SBATCH_RESOURCES="${SBATCH_RESOURCES:---gres=gpu:1}"
DRY_RUN="${DRY_RUN:-0}"

# -----------------------------
# Core run settings
# -----------------------------
MODEL_CONFIG="${MODEL_CONFIG:-composition_independent}"
SEED="${SEED:-42}"
FUSION_GATE="${FUSION_GATE:-0.2}"
SLIM_PROJECTOR="${SLIM_PROJECTOR:-0}"

OUTPUT_DIR="${OUTPUT_DIR:-checkpoints/composition_level2_full_32k}"
EPOCHS="${EPOCHS:-10}"
MAX_SAMPLES="${MAX_SAMPLES:-0}"     # 0 => full dataset
LR="${LR:-5e-5}"
BATCH_SIZE="${BATCH_SIZE:-1}"
NUM_AUDIO_TOKENS="${NUM_AUDIO_TOKENS:-8}"
EVAL_MODALITIES="${EVAL_MODALITIES:-text,audio,image,both}"
FUSION_LAYERS="${FUSION_LAYERS:-}"
AUDIO_FUSION_LAYERS="${AUDIO_FUSION_LAYERS:-}"
VISION_FUSION_LAYERS="${VISION_FUSION_LAYERS:-}"

# Initialize from existing independent checkpoint
INIT_AUDIO_CKPT="${INIT_AUDIO_CKPT:-checkpoints/comp_indep_additive_v1/best_model.pt}"
INIT_VISION_CKPT="${INIT_VISION_CKPT:-checkpoints/comp_indep_additive_v1/best_model.pt}"

# Learned gates
LEARNED_GATE="${LEARNED_GATE:-1}"
LEARNED_GATE_INIT="${LEARNED_GATE_INIT:-2.0}"
TRAIN_GATES_ONLY="${TRAIN_GATES_ONLY:-0}"

# Optional interaction correction mixer (ICM) sidecar
ICM_ENABLE="${ICM_ENABLE:-0}"
ICM_DIM="${ICM_DIM:-512}"
ICM_HEADS="${ICM_HEADS:-8}"
ICM_LAYERS="${ICM_LAYERS:-1}"
ICM_DROPOUT="${ICM_DROPOUT:-0.1}"
ICM_GATE_INIT="${ICM_GATE_INIT:--2.0}"
ICM_MIN_MODALITIES="${ICM_MIN_MODALITIES:-2}"
ICM_UTIL_TARGET="${ICM_UTIL_TARGET:-0.7}"

# Transport-mitigation architecture defaults (derivation-prescribed)
DELTA_NORM_CAP_RATIO="${DELTA_NORM_CAP_RATIO:-0.10}"
DELTA_NORM_CAP_EPS="${DELTA_NORM_CAP_EPS:-1e-6}"
GATE_DEPTH_DECAY="${GATE_DEPTH_DECAY:-1.0}"
AUDIO_GATE_DEPTH_DECAY="${AUDIO_GATE_DEPTH_DECAY:-0.95}"
VISION_GATE_DEPTH_DECAY="${VISION_GATE_DEPTH_DECAY:-0.97}"

# -----------------------------
# Compatibility objectives
# -----------------------------
COMPAT_REG_ENABLE="${COMPAT_REG_ENABLE:-1}"
COMPAT_REG_LAMBDA="${COMPAT_REG_LAMBDA:-0.05}"
COMPAT_REG_RANK="${COMPAT_REG_RANK:-8}"
COMPAT_REG_AUDIO_SAMPLES="${COMPAT_REG_AUDIO_SAMPLES:-256}"
COMPAT_REG_WEIGHT_BY_SHIFT_NORM="${COMPAT_REG_WEIGHT_BY_SHIFT_NORM:-1}"
COMPAT_REG_LAYERS="${COMPAT_REG_LAYERS:-}"

COMPAT_ADD_REG_ENABLE="${COMPAT_ADD_REG_ENABLE:-1}"
COMPAT_ADD_REG_LAMBDA="${COMPAT_ADD_REG_LAMBDA:-0.01}"
COMPAT_ADD_REG_EVERY="${COMPAT_ADD_REG_EVERY:-200}"
COMPAT_ADD_REG_NORMALIZE="${COMPAT_ADD_REG_NORMALIZE:-1}"
COMPAT_ADD_BANK_SIZE="${COMPAT_ADD_BANK_SIZE:-64}"
COMPAT_ADD_REG_LAYERS="${COMPAT_ADD_REG_LAYERS:-}"

COMPAT_TRANSPORT_ENABLE="${COMPAT_TRANSPORT_ENABLE:-1}"
COMPAT_TRANSPORT_LAMBDA="${COMPAT_TRANSPORT_LAMBDA:-0.02}"
COMPAT_TRANSPORT_CAP="${COMPAT_TRANSPORT_CAP:-0.0}"
COMPAT_TRANSPORT_NORMALIZE="${COMPAT_TRANSPORT_NORMALIZE:-1}"
COMPAT_TRANSPORT_LAYERS="${COMPAT_TRANSPORT_LAYERS:-}"

# ICM-specific objectives (all off by default for derivation-only runs)
COMPAT_ICM_CANCEL_ENABLE="${COMPAT_ICM_CANCEL_ENABLE:-0}"
COMPAT_ICM_CANCEL_LAMBDA="${COMPAT_ICM_CANCEL_LAMBDA:-0.02}"
COMPAT_ICM_CANCEL_LOSS_TYPE="${COMPAT_ICM_CANCEL_LOSS_TYPE:-mse}"
COMPAT_ICM_CANCEL_LOGIT_TEMP="${COMPAT_ICM_CANCEL_LOGIT_TEMP:-1.0}"
COMPAT_ICM_CANCEL_START_STEP="${COMPAT_ICM_CANCEL_START_STEP:-0}"
COMPAT_ICM_NOHARM_START_STEP="${COMPAT_ICM_NOHARM_START_STEP:-0}"
COMPAT_ICM_UTIL_LAMBDA="${COMPAT_ICM_UTIL_LAMBDA:-0.0}"
COMPAT_ICM_UTIL_START_STEP="${COMPAT_ICM_UTIL_START_STEP:-0}"
COMPAT_ICM_IDENTITY_LAMBDA="${COMPAT_ICM_IDENTITY_LAMBDA:-0.01}"
COMPAT_ICM_SMALL_LAMBDA="${COMPAT_ICM_SMALL_LAMBDA:-0.001}"

COMPAT_GATE_ADD_ENABLE="${COMPAT_GATE_ADD_ENABLE:-1}"
COMPAT_GATE_ADD_LAMBDA="${COMPAT_GATE_ADD_LAMBDA:-0.01}"
COMPAT_GATE_PAIRING="${COMPAT_GATE_PAIRING:-zip}"
COMPAT_GATE_TARGET_MODE="${COMPAT_GATE_TARGET_MODE:-inverse_rho}"
COMPAT_GATE_PRODUCT_TARGET="${COMPAT_GATE_PRODUCT_TARGET:--1}"
COMPAT_GATE_RHO_BETA="${COMPAT_GATE_RHO_BETA:-2.0}"
COMPAT_GATE_MIN_EFFECTIVE="${COMPAT_GATE_MIN_EFFECTIVE:-0.02}"
COMPAT_GATE_FLOOR_LAMBDA="${COMPAT_GATE_FLOOR_LAMBDA:-0.05}"

# Keep auxiliary objectives OFF by default for derivation-only runs.
COMPAT_NOHARM_ENABLE="${COMPAT_NOHARM_ENABLE:-0}"
COMPAT_NOHARM_LAMBDA="${COMPAT_NOHARM_LAMBDA:-0.02}"
COMPAT_NOHARM_MARGIN="${COMPAT_NOHARM_MARGIN:-0.0}"
COMPAT_NOHARM_USE_BEST_SINGLE="${COMPAT_NOHARM_USE_BEST_SINGLE:-1}"

COMPAT_LOGIT_FUSION_ENABLE="${COMPAT_LOGIT_FUSION_ENABLE:-0}"
COMPAT_LOGIT_FUSION_LAMBDA="${COMPAT_LOGIT_FUSION_LAMBDA:-0.02}"
COMPAT_LOGIT_FUSION_CONF_TEMP="${COMPAT_LOGIT_FUSION_CONF_TEMP:-0.5}"

COMPAT_POE_ENABLE="${COMPAT_POE_ENABLE:-0}"
COMPAT_POE_LAMBDA="${COMPAT_POE_LAMBDA:-0.02}"
COMPAT_POE_WEIGHT_TEMP="${COMPAT_POE_WEIGHT_TEMP:-0.5}"
COMPAT_POE_LOSS_TYPE="${COMPAT_POE_LOSS_TYPE:-kl}"
COMPAT_POE_LOGIT_TEMP="${COMPAT_POE_LOGIT_TEMP:-1.0}"

COMPAT_ROUTING_ENABLE="${COMPAT_ROUTING_ENABLE:-0}"
COMPAT_ROUTING_MIN_SCALE="${COMPAT_ROUTING_MIN_SCALE:-0.25}"
COMPAT_ROUTING_MAX_SCALE="${COMPAT_ROUTING_MAX_SCALE:-1.0}"

# -----------------------------
# Logging
# -----------------------------
WANDB="${WANDB:-1}"
WANDB_PROJECT="${WANDB_PROJECT:-SAFE-Composition}"
WANDB_RUN_NAME="${WANDB_RUN_NAME:-comp_level2_full32k_derivation_only_s${SEED}_$(date +%m%d_%H%M)}"
WANDB_TAGS="${WANDB_TAGS:-composition,level2,full32k,derivation_only,no_poe,transport_bound}"

exports=(
  "ALL"
  "SAFE_ROOT=$SAFE_ROOT"
  "MODEL_CONFIG=$MODEL_CONFIG"
  "SEED=$SEED"
  "FUSION_GATE=$FUSION_GATE"
  "SLIM_PROJECTOR=$SLIM_PROJECTOR"
  "OUTPUT_DIR=$OUTPUT_DIR"
  "EPOCHS=$EPOCHS"
  "MAX_SAMPLES=$MAX_SAMPLES"
  "LR=$LR"
  "BATCH_SIZE=$BATCH_SIZE"
  "NUM_AUDIO_TOKENS=$NUM_AUDIO_TOKENS"
  "EVAL_MODALITIES=$EVAL_MODALITIES"
  "FUSION_LAYERS=$FUSION_LAYERS"
  "AUDIO_FUSION_LAYERS=$AUDIO_FUSION_LAYERS"
  "VISION_FUSION_LAYERS=$VISION_FUSION_LAYERS"
  "INIT_AUDIO_CKPT=$INIT_AUDIO_CKPT"
  "INIT_VISION_CKPT=$INIT_VISION_CKPT"
  "LEARNED_GATE=$LEARNED_GATE"
  "LEARNED_GATE_INIT=$LEARNED_GATE_INIT"
  "TRAIN_GATES_ONLY=$TRAIN_GATES_ONLY"
  "ICM_ENABLE=$ICM_ENABLE"
  "ICM_DIM=$ICM_DIM"
  "ICM_HEADS=$ICM_HEADS"
  "ICM_LAYERS=$ICM_LAYERS"
  "ICM_DROPOUT=$ICM_DROPOUT"
  "ICM_GATE_INIT=$ICM_GATE_INIT"
  "ICM_MIN_MODALITIES=$ICM_MIN_MODALITIES"
  "ICM_UTIL_TARGET=$ICM_UTIL_TARGET"
  "DELTA_NORM_CAP_RATIO=$DELTA_NORM_CAP_RATIO"
  "DELTA_NORM_CAP_EPS=$DELTA_NORM_CAP_EPS"
  "GATE_DEPTH_DECAY=$GATE_DEPTH_DECAY"
  "AUDIO_GATE_DEPTH_DECAY=$AUDIO_GATE_DEPTH_DECAY"
  "VISION_GATE_DEPTH_DECAY=$VISION_GATE_DEPTH_DECAY"
  "COMPAT_REG_ENABLE=$COMPAT_REG_ENABLE"
  "COMPAT_REG_LAMBDA=$COMPAT_REG_LAMBDA"
  "COMPAT_REG_RANK=$COMPAT_REG_RANK"
  "COMPAT_REG_AUDIO_SAMPLES=$COMPAT_REG_AUDIO_SAMPLES"
  "COMPAT_REG_WEIGHT_BY_SHIFT_NORM=$COMPAT_REG_WEIGHT_BY_SHIFT_NORM"
  "COMPAT_ADD_REG_ENABLE=$COMPAT_ADD_REG_ENABLE"
  "COMPAT_ADD_REG_LAMBDA=$COMPAT_ADD_REG_LAMBDA"
  "COMPAT_ADD_REG_EVERY=$COMPAT_ADD_REG_EVERY"
  "COMPAT_ADD_REG_NORMALIZE=$COMPAT_ADD_REG_NORMALIZE"
  "COMPAT_ADD_BANK_SIZE=$COMPAT_ADD_BANK_SIZE"
  "COMPAT_TRANSPORT_ENABLE=$COMPAT_TRANSPORT_ENABLE"
  "COMPAT_TRANSPORT_LAMBDA=$COMPAT_TRANSPORT_LAMBDA"
  "COMPAT_TRANSPORT_CAP=$COMPAT_TRANSPORT_CAP"
  "COMPAT_TRANSPORT_NORMALIZE=$COMPAT_TRANSPORT_NORMALIZE"
  "COMPAT_ICM_CANCEL_ENABLE=$COMPAT_ICM_CANCEL_ENABLE"
  "COMPAT_ICM_CANCEL_LAMBDA=$COMPAT_ICM_CANCEL_LAMBDA"
  "COMPAT_ICM_CANCEL_LOSS_TYPE=$COMPAT_ICM_CANCEL_LOSS_TYPE"
  "COMPAT_ICM_CANCEL_LOGIT_TEMP=$COMPAT_ICM_CANCEL_LOGIT_TEMP"
  "COMPAT_ICM_CANCEL_START_STEP=$COMPAT_ICM_CANCEL_START_STEP"
  "COMPAT_ICM_NOHARM_START_STEP=$COMPAT_ICM_NOHARM_START_STEP"
  "COMPAT_ICM_UTIL_LAMBDA=$COMPAT_ICM_UTIL_LAMBDA"
  "COMPAT_ICM_UTIL_START_STEP=$COMPAT_ICM_UTIL_START_STEP"
  "COMPAT_ICM_IDENTITY_LAMBDA=$COMPAT_ICM_IDENTITY_LAMBDA"
  "COMPAT_ICM_SMALL_LAMBDA=$COMPAT_ICM_SMALL_LAMBDA"
  "COMPAT_GATE_ADD_ENABLE=$COMPAT_GATE_ADD_ENABLE"
  "COMPAT_GATE_ADD_LAMBDA=$COMPAT_GATE_ADD_LAMBDA"
  "COMPAT_GATE_PAIRING=$COMPAT_GATE_PAIRING"
  "COMPAT_GATE_TARGET_MODE=$COMPAT_GATE_TARGET_MODE"
  "COMPAT_GATE_PRODUCT_TARGET=$COMPAT_GATE_PRODUCT_TARGET"
  "COMPAT_GATE_RHO_BETA=$COMPAT_GATE_RHO_BETA"
  "COMPAT_GATE_MIN_EFFECTIVE=$COMPAT_GATE_MIN_EFFECTIVE"
  "COMPAT_GATE_FLOOR_LAMBDA=$COMPAT_GATE_FLOOR_LAMBDA"
  "COMPAT_NOHARM_ENABLE=$COMPAT_NOHARM_ENABLE"
  "COMPAT_NOHARM_LAMBDA=$COMPAT_NOHARM_LAMBDA"
  "COMPAT_NOHARM_MARGIN=$COMPAT_NOHARM_MARGIN"
  "COMPAT_NOHARM_USE_BEST_SINGLE=$COMPAT_NOHARM_USE_BEST_SINGLE"
  "COMPAT_LOGIT_FUSION_ENABLE=$COMPAT_LOGIT_FUSION_ENABLE"
  "COMPAT_LOGIT_FUSION_LAMBDA=$COMPAT_LOGIT_FUSION_LAMBDA"
  "COMPAT_LOGIT_FUSION_CONF_TEMP=$COMPAT_LOGIT_FUSION_CONF_TEMP"
  "COMPAT_POE_ENABLE=$COMPAT_POE_ENABLE"
  "COMPAT_POE_LAMBDA=$COMPAT_POE_LAMBDA"
  "COMPAT_POE_WEIGHT_TEMP=$COMPAT_POE_WEIGHT_TEMP"
  "COMPAT_POE_LOSS_TYPE=$COMPAT_POE_LOSS_TYPE"
  "COMPAT_POE_LOGIT_TEMP=$COMPAT_POE_LOGIT_TEMP"
  "COMPAT_ROUTING_ENABLE=$COMPAT_ROUTING_ENABLE"
  "COMPAT_ROUTING_MIN_SCALE=$COMPAT_ROUTING_MIN_SCALE"
  "COMPAT_ROUTING_MAX_SCALE=$COMPAT_ROUTING_MAX_SCALE"
  "WANDB=$WANDB"
  "WANDB_PROJECT=$WANDB_PROJECT"
  "WANDB_RUN_NAME=$WANDB_RUN_NAME"
  "WANDB_TAGS=$WANDB_TAGS"
)

if [[ -n "$COMPAT_REG_LAYERS" ]]; then
  exports+=("COMPAT_REG_LAYERS=$COMPAT_REG_LAYERS")
fi
if [[ -n "$COMPAT_ADD_REG_LAYERS" ]]; then
  exports+=("COMPAT_ADD_REG_LAYERS=$COMPAT_ADD_REG_LAYERS")
fi
if [[ -n "$COMPAT_TRANSPORT_LAYERS" ]]; then
  exports+=("COMPAT_TRANSPORT_LAYERS=$COMPAT_TRANSPORT_LAYERS")
fi

export_str="$(IFS=,; echo "${exports[*]}")"
read -r -a sbatch_args <<< "$SBATCH_RESOURCES"
cmd=(sbatch "${sbatch_args[@]}" --export="$export_str" "$TRAIN_SCRIPT")

echo "[submit] SAFE_ROOT=$SAFE_ROOT"
echo "[submit] OUTPUT_DIR=$OUTPUT_DIR"
echo "[submit] RUN_NAME=$WANDB_RUN_NAME"
echo "[submit] DATA=full (MAX_SAMPLES=$MAX_SAMPLES)"
echo "[submit] command: ${cmd[*]}"

if [[ "$DRY_RUN" == "1" ]]; then
  exit 0
fi

"${cmd[@]}"
